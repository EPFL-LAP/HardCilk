package SoftwareUtil

import Descriptors._
import HardCilk.OutputLayout
import Util.BuilderConfig
import Util.HardCilkEmitterUtil.{RtlGenResult, writeFile}

/**
  * Writes the `README.md` that explains the tree the emitter just produced.
  *
  * It documents only the flows this run actually built, so it can be trusted as
  * the record of what a given output directory contains and how to drive it.
  */
object ReadmeGenerator {

  def generate(
      descriptor: FullSysGenDescriptor,
      jsonName: String,
      layout: OutputLayout,
      cfg: BuilderConfig,
      commandLine: String,
      sharedRtl: Option[RtlGenResult],
      vitisRtl: Option[RtlGenResult]
  ): Unit = {
    val sb = new StringBuilder

    sb ++= s"# ${descriptor.name}\n\n"
    sb ++= "Generated by the HardCilk architecture generator.\n\n"
    sb ++= "```\nHardCilk " + commandLine + "\n```\n\n"

    sb ++= summarySection(descriptor, cfg, sharedRtl, vitisRtl)
    sb ++= layoutSection(cfg)

    if (cfg.questa) sb ++= questaSection(descriptor, jsonName, cfg)
    if (cfg.pcie) sb ++= pcieSection(descriptor, jsonName, cfg)
    if (cfg.vitis) sb ++= vitisSection(descriptor, jsonName, cfg)
    if (cfg.software) sb ++= softwareSection(jsonName, cfg)

    sb ++= choosingSection(cfg)
    sb ++= registerMapSection(descriptor, cfg)

    writeFile(s"${layout.root}/README.md", sb.toString())
    println(s"[ReadmeGenerator] Emitted README.md to: ${layout.root}")
  }

  // ─── Summary ────────────────────────────────────────────────────────────────

  private def summarySection(
      descriptor: FullSysGenDescriptor,
      cfg: BuilderConfig,
      sharedRtl: Option[RtlGenResult],
      vitisRtl: Option[RtlGenResult]
  ): String = {
    val flows = Seq(
      if (cfg.questa) Some("QuestaSim simulation (`questa/`)") else None,
      if (cfg.pcie) Some("Vivado XDMA/PCIe design (`pcie/`)") else None,
      if (cfg.vitis) Some("Vitis xclbin (`vitis/`)") else None
    ).flatten

    val sb = new StringBuilder
    sb ++= "## What is in here\n\n"
    sb ++= flows.map(f => s"- $f\n").mkString
    if (cfg.software) sb ++= "- C++ driver and host software (`software/`)\n"
    sb ++= "\n| | |\n|---|---|\n"
    sb ++= s"| Target device | `${descriptor.fpgaModel}` |\n"
    sb ++= s"| Target frequency | ${descriptor.targetFrequency} MHz |\n"
    sb ++= s"| Tasks | ${descriptor.taskDescriptors.map(_.name).mkString(", ")} |\n"
    sb ++= s"| HBM ports (`-r`) | ${cfg.hbmPorts} |\n"
    sharedRtl.foreach(r => sb ++= s"| Exported memory masters | ${r.numHbmPortExports} |\n")
    vitisRtl.foreach(r => sb ++= s"| Exported memory masters (Vitis) | ${r.numHbmPortExports} |\n")
    sb ++= s"| RAMA striping | ${if (cfg.ramaStriping) "on" else "off"} |\n"
    sb ++= s"| Raw HBM ports | ${if (cfg.rawHbmPorts) "on" else "off"} |\n"
    sb ++= s"| Debug counters | ${if (cfg.debug) "on" else "off"} |\n"
    sb ++= "\n"

    if (cfg.questa && cfg.pcie) {
      sb ++= "The QuestaSim and PCIe flows share the RTL in `rtl/`: both drive the design's " +
        "native 64-bit AXI-Lite management port, so the elaborated Verilog is identical. They " +
        "each build their own Vivado project in their own directory and can be run " +
        "independently, in either order.\n\n"
    }
    if (cfg.vitis && (cfg.questa || cfg.pcie)) {
      sb ++= "The Vitis flow has its own RTL in `vitis/rtl/`. Vitis reserves the first `0x10` " +
        "bytes of a kernel's register space for its `ap_ctrl` block and drives the control port " +
        "at 32 bits, so its design is not interchangeable with the one in `rtl/`.\n\n"
    }
    sb.toString()
  }

  private def layoutSection(cfg: BuilderConfig): String = {
    val sb = new StringBuilder
    sb ++= "## Layout\n\n```\n"
    if (cfg.needsSharedRtl) sb ++= "rtl/         RTL shared by the QuestaSim and PCIe flows\n"
    if (cfg.questa) sb ++= "questa/      QuestaSim project  -> ./simulate.sh\n"
    if (cfg.pcie) sb ++= "pcie/        Vivado block design -> ./build.sh\n"
    if (cfg.vitis) sb ++= "vitis/       Vitis xclbin project -> make TARGET=hw|hw_emu\n"
    if (cfg.software) sb ++= "software/    C++ driver and host software -> cmake\n"
    sb ++= "```\n\n"
    sb.toString()
  }

  // ─── Per-flow instructions ──────────────────────────────────────────────────

  private def questaSection(
      descriptor: FullSysGenDescriptor,
      jsonName: String,
      cfg: BuilderConfig
  ): String = {
    val sb = new StringBuilder
    sb ++= "## QuestaSim simulation\n\n"
    sb ++= "```sh\ncd questa\n./simulate.sh\n```\n\n"
    sb ++= s"`simulate.sh` builds the block design with Vivado (`${descriptor.name}_questa.tcl`), " +
      "launches the simulation, copies `simulate.do` into the generated simulation directory and " +
      "starts `vsim`. It stops at the first failing step.\n\n"
    sb ++= "Requirements:\n\n"
    sb ++= "- Vivado 2024.1 under `/alpha/tools/Xilinx`\n"
    sb ++= "- QuestaSim with Xilinx libraries compiled into `/alpha/questa`\n"
    if (cfg.software)
      sb ++= s"- The testbench sources: `software/projects/$jsonName/src/questa_main.cpp` and its " +
        "`include/test_bench_questa.h`. They are compiled by `sccom` from `simulate.do`, not by " +
        "CMake, so there is no `_questa` CMake target.\n"
    sb ++= "\n"
    sb ++= "**This is the flow to use for performance analysis** — it is the only one that models " +
      "the real HBM controller, the interconnect and the RAMA path cycle by cycle. It is also far " +
      "slower than the alternatives, so size the input data down accordingly.\n\n"
    sb ++= "> **Tip:** simulated memory starts out as zeroes, so the driver does not need to write " +
      "zeros into freshly allocated buffers. Skipping those writes removes a large amount of DPI " +
      "traffic and is usually the single biggest saving in simulation time — see " +
      "`software/driver/include/memIO_questa.h`.\n\n"
    sb.toString()
  }

  private def pcieSection(
      descriptor: FullSysGenDescriptor,
      jsonName: String,
      cfg: BuilderConfig
  ): String = {
    val sb = new StringBuilder
    sb ++= "## PCIe bitstream (Vivado + XDMA)\n\n"
    sb ++= "```sh\ncd pcie\n./build.sh            # build the block design\n" +
      "./build.sh --gui      # open it in the Vivado GUI\n" +
      "./build.sh --impl     # synthesis, place & route and bitstream, headless\n```\n\n"
    sb ++= s"The bitstream lands in `${descriptor.name}_vivado_project/project_1.runs/impl_1/*.bit`.\n\n"
    sb ++= s"`${descriptor.name}_floorplan.xdc` pins the PEs and the memory path to SLRs and is " +
      s"read implementation-only; `${descriptor.name}_drc_waivers.tcl` runs as an `opt_design` " +
      "pre-hook. Both are applied automatically by the project script.\n\n"
    if (cfg.software)
      sb ++= s"Host side: build the `${jsonName}_pcie` target in `software/`. It talks to the card " +
        "through the `xdma` kernel driver and resets the design by writing the GPIO at " +
        "`RESET_ADDR = 0x8000` (that segment is pinned in the block design to match).\n\n"
    if (!cfg.ramaStriping)
      sb ++= "> RAMA striping is **off** in this build: each memory port reaches its own HBM " +
        "pseudo-channel pair through a 1:1 SmartConnect, and the host DMA path gets a port of its " +
        "own. Rebuild with `--rama-striping` to spread every port's traffic across all 32 pseudo " +
        "channels, which is usually a large win for random-access workloads.\n\n"
    else
      sb ++= "> RAMA striping is **on**: every memory port and the host DMA path go through a RAMA " +
        "IP that spreads 64-byte fragments across all 32 HBM pseudo channels. The host traverses " +
        "an identically-configured RAMA on purpose — striping permutes addresses, so a host that " +
        "reached HBM directly would not see the same bytes the PEs do.\n\n"
    sb.toString()
  }

  private def vitisSection(
      descriptor: FullSysGenDescriptor,
      jsonName: String,
      cfg: BuilderConfig
  ): String = {
    val sb = new StringBuilder
    sb ++= "## Vitis xclbin\n\n"
    sb ++= "```sh\ncd vitis\nmake TARGET=hw_emu     # emulation xclbin, minutes\n" +
      "make TARGET=hw         # real bitstream, hours\n```\n\n"
    sb ++= "Each target keeps its own `.xo`, build directory and connectivity config, so the two " +
      "can be built in either order without invalidating each other. `make clean` removes both.\n\n"
    sb ++= "**`hw_emu` is for functional verification only.** Its memory model answers every " +
      "access with roughly uniform latency and no bank contention, so throughput and cycle counts " +
      "from an emulation run say nothing about how the design will perform on hardware. Use it to " +
      "confirm the design computes the right answer, then use the QuestaSim flow (or real " +
      "hardware) for performance numbers.\n\n"
    if (cfg.software) {
      sb ++= s"Host side: build the `${jsonName}_xrt` target in `software/`. It loads the xclbin " +
        "through XRT.\n\n"
      sb ++= "> The XRT target links against AlveoLink. `AL_PATH` at the top of " +
        s"`software/projects/$jsonName/CMakeLists.txt` must point at a real AlveoLink checkout, " +
        "or that target will not configure.\n\n"
    }
    sb ++= "The Vitis flow has no interconnect of its own to tune: `v++` builds it from the " +
      "`sp=` lines in `src/cfg/conn_u55c.cfg`, which is why RAMA cannot be inserted here and " +
      "`--rama-striping` does not apply.\n\n"
    sb.toString()
  }

  private def softwareSection(jsonName: String, cfg: BuilderConfig): String = {
    val sb = new StringBuilder
    sb ++= "## Software\n\n"
    sb ++= "```sh\ncd software\ncmake -B build\ncmake --build build\n```\n\n"
    val targets = Seq(
      if (cfg.pcie) Some(s"`${jsonName}_pcie` — PCIe/XDMA host program") else None,
      if (cfg.vitis) Some(s"`${jsonName}_xrt` — XRT host program for the xclbin") else None
    ).flatten
    if (targets.nonEmpty) sb ++= "Targets:\n\n" + targets.map(t => s"- $t\n").mkString + "\n"
    if (cfg.questa)
      sb ++= s"The QuestaSim testbench is not a CMake target: `sccom` compiles " +
        s"`projects/$jsonName/src/questa_main.cpp` directly from `questa/simulate.do`.\n\n"
    sb ++= "All backends share `driver/` — `hardCilkDriver` only ever reads and writes 64-bit " +
      "registers at the management base addresses, so a flow differs only in its `Memory` " +
      "implementation (`memIO_pcie.h`, `memIO_xrt.h`, `memIO_questa.h`) and its `main()`.\n\n"
    sb ++= s"The generated `FullSysGenDescriptor.h` exists in two variants under " +
      s"`projects/$jsonName/include/gen/`: `nonvitis/` for the QuestaSim and PCIe builds and " +
      "`vitis/` for the XRT build, whose addresses are shifted by `0x10`. CMake puts the right " +
      "one on each target's include path, so the driver sources are identical.\n\n"
    sb ++= "After a change to the JSON that only the host reads (queue capacities, for example), " +
      "rewrite just these headers with `-c` instead of regenerating: it elaborates nothing, so a " +
      "finished place-and-route stays valid.\n\n"
    sb ++= s"```sh\nsbt \"runMain HardCilk.HardCilkEmitter <json> -o <this directory> -c\"\n```\n\n"
    sb.toString()
  }

  // ─── Guidance ───────────────────────────────────────────────────────────────

  private def choosingSection(cfg: BuilderConfig): String = {
    if (Seq(cfg.questa, cfg.pcie, cfg.vitis).count(identity) < 2) return ""
    val sb = new StringBuilder
    sb ++= "## Which flow to use\n\n"
    sb ++= "| Question | Flow |\n|---|---|\n"
    if (cfg.vitis) sb ++= "| Does it compute the right answer? | Vitis `hw_emu` — fastest turnaround |\n"
    if (cfg.questa) sb ++= "| How many cycles does it take, and where does memory stall? | QuestaSim — accurate, slow, small inputs |\n"
    if (cfg.pcie) sb ++= "| Run it on the card at full speed | PCIe bitstream |\n"
    if (cfg.vitis) sb ++= "| Run it on the card through XRT | Vitis `hw` |\n"
    sb ++= "\n"
    sb.toString()
  }

  private def registerMapSection(rawDescriptor: FullSysGenDescriptor, cfg: BuilderConfig): String = {
    // `mgmtBaseAddresses` is a mutable field of TaskDescriptor and copied
    // descriptors share those instances, so whichever flow elaborated last has
    // left its convention on them. Re-run the body for the native one before
    // reading the addresses back.
    val descriptor = rawDescriptor.copy(vitisMgmtConvention = false)
    val sb = new StringBuilder
    sb ++= "## Management register map\n\n"
    sb ++= "Every virtual server gets a 64-byte block (`index << 6`), numbered across all tasks in " +
      "descriptor order. The addresses below are the ones the QuestaSim and PCIe builds use"
    sb ++= (if (cfg.vitis) "; the Vitis build shifts every one of them by `0x10`, because Vitis " +
      "reserves the first `0x10` bytes for the kernel's own `ap_ctrl` block.\n\n"
    else ".\n\n")

    sb ++= "| Task | Scheduler servers | Spawner servers | Allocation servers | Memory allocators |\n"
    sb ++= "|---|---|---|---|---|\n"
    descriptor.taskDescriptors.foreach { task =>
      val m = task.mgmtBaseAddresses
      def fmt(xs: Seq[Int]) = if (xs.isEmpty) "—" else xs.map(a => f"0x$a%X").mkString(", ")
      sb ++= s"| `${task.name}` | ${fmt(m.schedulerServersBaseAddresses)} | " +
        s"${fmt(m.spawnerServersBaseAddresses)} | ${fmt(m.allocationServersBaseAddresses)} | " +
        s"${fmt(m.memoryAllocatorServersBaseAddresses)} |\n"
    }
    sb ++= "\n"
    sb ++= "Spawner servers share the scheduler register layout, so their addresses also appear " +
      "in the scheduler column; the separate column only exists so the host can tell the two " +
      "apart. Register offsets within a block are defined in " +
      "`driver/include/hardCilkDriver.h`.\n"
    sb.toString()
  }
}
