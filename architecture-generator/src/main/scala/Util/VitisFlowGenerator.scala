package Util

import Descriptors._
import Util.HardCilkEmitterUtil.writeFile
import java.nio.file.{Files, Paths, StandardCopyOption}

object VitisFlowGenerator {

  def generate(
      descriptor: FullSysGenDescriptor,
      outputDir: String,
      reduceAxi: Int,
      rtlDir: String
  ): Unit = {
    Files.createDirectories(Paths.get(s"$outputDir/scripts"))
    Files.createDirectories(Paths.get(s"$outputDir/src/cfg"))
    Files.createDirectories(Paths.get(s"$outputDir/src/xml"))
    Files.createDirectories(Paths.get(s"$outputDir/src/IP"))

    // Copy all flat files from the RTL output directory into src/IP/
    val rtlPath = Paths.get(rtlDir)
    if (Files.exists(rtlPath)) {
      Files.list(rtlPath)
        .filter(p => Files.isRegularFile(p))
        .forEach(src =>
          Files.copy(src, Paths.get(s"$outputDir/src/IP/${src.getFileName}"),
            StandardCopyOption.REPLACE_EXISTING)
        )
      // Vitis expects active-low reset_n; patch the top-level module in-place
      patchVitisReset(descriptor, outputDir)
    } else {
      println(s"[VitisFlowGenerator] WARNING: RTL directory not found at $rtlDir — src/IP will be empty")
    }

    writeFile(s"$outputDir/Makefile",         makefile(descriptor, reduceAxi))
    writeFile(s"$outputDir/scripts/gen_xo.tcl",          genXoTcl(descriptor))
    writeFile(s"$outputDir/scripts/package_kernel.tcl",  packageKernelTcl(descriptor, reduceAxi))
    writeFile(s"$outputDir/scripts/clear_drc_errors.tcl", clearDrcTcl(descriptor))
    writeFile(s"$outputDir/src/cfg/conn_u55c.cfg",       connCfg(descriptor, reduceAxi))
    writeFile(s"$outputDir/src/cfg/conn_u55c_emu.cfg",   connCfgEmu(descriptor, reduceAxi))
    writeFile(s"$outputDir/src/xml/user_0.xml",          userXml(descriptor, reduceAxi))
  }

  // ─── Makefile ────────────────────────────────────────────────────────────────

